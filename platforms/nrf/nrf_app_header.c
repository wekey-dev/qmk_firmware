// Header of the QMK app image (struct nrf_app_header, nrf_core_api.h).
//
// Placed at the start of the QMK partition. The core validates it before
// starting the app and reads the keyboard description from it:
//   - device identity (VID/PID, version, manufacturer, product name), from
//     keyboard.json through QMK's generated defines;
//   - battery measurement, from the keyboard's config.h (NRF_BATTERY_*);
//   - power / clock hardware, from the keyboard's config.h (see below).

#include <stdint.h>
#include "nrf_core.h"
#include "gpio.h"              /* pin names (P0_04...) and NO_PIN */
#include "nrf_core_abi_hash.h" /* from the core SDK */

/* Linker symbols (ld/nrf_app_common.ld) */
extern uint8_t __app_flash_start[], __app_ram_start[], __app_ram_end[];

void nrf_app_entry(const struct nrf_core_api *api); /* nrf_app.c */

#ifndef NRF_CHIP
#    error "NRF_CHIP must be defined by platforms/nrf/mcu_selection.mk"
#endif

/* Device identity, generated by QMK from keyboard.json:
 *   usb.vid -> VENDOR_ID, usb.pid -> PRODUCT_ID, usb.device_version -> DEVICE_VER,
 *   manufacturer -> MANUFACTURER, keyboard_name -> PRODUCT.
 * The core presents them on USB and BLE. 0 / "" = use the core's defaults. */
#ifndef PRODUCT
#    define PRODUCT ""
#endif
#ifndef MANUFACTURER
#    define MANUFACTURER ""
#endif
#ifndef VENDOR_ID
#    define VENDOR_ID 0
#endif
#ifndef PRODUCT_ID
#    define PRODUCT_ID 0
#endif
#ifndef DEVICE_VER
#    define DEVICE_VER 0
#endif

_Static_assert(sizeof(PRODUCT) <= NRF_APP_STR_MAX, "keyboard_name (PRODUCT) must be at most 31 characters");
_Static_assert(sizeof(MANUFACTURER) <= NRF_APP_STR_MAX, "manufacturer (MANUFACTURER) must be at most 31 characters");

static const char nrf_app_manufacturer[] = MANUFACTURER;

/* Battery measurement, declared in the keyboard's config.h:
 *
 *   #define NRF_BATTERY_METHOD NRF_BATTERY_DIVIDER   // NONE (default), DIVIDER, VDDH, VDD
 *
 *   DIVIDER only:
 *   #define NRF_BATTERY_PIN       P0_04     // divider output, AIN pin: P0_02..P0_05, P0_28..P0_31
 *   #define NRF_BATTERY_R_TOP     1000000   // ohms, battery -> pin
 *   #define NRF_BATTERY_R_BOTTOM  1000000   // ohms, pin -> GND
 *   #define NRF_BATTERY_EN_PIN    P0_05     // optional: powers the divider only while sampling
 *   #define NRF_BATTERY_EN_ACTIVE_LOW       // optional: enable pin is active low
 *   #define NRF_BATTERY_SETTLE_US 1000      // optional: wait after enabling (default 1000)
 *
 *   Level curve (all methods), optional:
 *   #define NRF_BATTERY_EMPTY_MV  2000      // linear 0 %..100 % between these;
 *   #define NRF_BATTERY_FULL_MV   3000      // default: LiPo curve 3.3 V..4.2 V
 */
#ifndef NRF_BATTERY_METHOD
#    define NRF_BATTERY_METHOD NRF_BATTERY_NONE
#endif

#if NRF_BATTERY_METHOD == NRF_BATTERY_DIVIDER
#    if !defined(NRF_BATTERY_PIN) || !defined(NRF_BATTERY_R_TOP) || !defined(NRF_BATTERY_R_BOTTOM)
#        error "NRF_BATTERY_DIVIDER needs NRF_BATTERY_PIN, NRF_BATTERY_R_TOP and NRF_BATTERY_R_BOTTOM"
#    endif
#    if NRF_BATTERY_R_BOTTOM <= 0
#        error "NRF_BATTERY_R_BOTTOM must be > 0"
#    endif
#elif NRF_BATTERY_METHOD != NRF_BATTERY_NONE && NRF_BATTERY_METHOD != NRF_BATTERY_VDDH && NRF_BATTERY_METHOD != NRF_BATTERY_VDD
#    error "NRF_BATTERY_METHOD must be NRF_BATTERY_NONE, NRF_BATTERY_DIVIDER, NRF_BATTERY_VDDH or NRF_BATTERY_VDD"
#endif

#ifndef NRF_BATTERY_PIN
#    define NRF_BATTERY_PIN NO_PIN
#endif
#ifndef NRF_BATTERY_R_TOP
#    define NRF_BATTERY_R_TOP 0
#endif
#ifndef NRF_BATTERY_R_BOTTOM
#    define NRF_BATTERY_R_BOTTOM 0
#endif
#ifndef NRF_BATTERY_EN_PIN
#    define NRF_BATTERY_EN_PIN NO_PIN
#endif
#ifdef NRF_BATTERY_EN_ACTIVE_LOW
#    define NRF_BATTERY_EN_LOW 1
#else
#    define NRF_BATTERY_EN_LOW 0
#endif
#ifndef NRF_BATTERY_SETTLE_US
#    define NRF_BATTERY_SETTLE_US 1000
#endif
#ifndef NRF_BATTERY_EMPTY_MV
#    define NRF_BATTERY_EMPTY_MV 0
#endif
#ifndef NRF_BATTERY_FULL_MV
#    define NRF_BATTERY_FULL_MV 0
#endif
#if NRF_BATTERY_FULL_MV != 0 && NRF_BATTERY_FULL_MV <= NRF_BATTERY_EMPTY_MV
#    error "NRF_BATTERY_FULL_MV must be above NRF_BATTERY_EMPTY_MV"
#endif

/* Power / clock hardware, declared in the keyboard's config.h:
 *
 *   #define NRF_LFCLK_CRYSTAL     // 32.768 kHz crystal on P0.00 / P0.01
 *   #define NRF_POWER_DCDC_REG1   // DC/DC inductor on DCC (+ DEC4): core enables REG1 DC/DC
 *   #define NRF_POWER_DCDC_REG0   // DC/DC inductor on DCCH (VDDH supply): core enables REG0 DC/DC
 *
 * NRF_LFCLK_CRYSTAL selects which core the keyboard needs: nrf/<soc>/xtal
 * with it, nrf/<soc> (RC oscillator) without; the core's build picks
 * it from this header. Declare DC/DC only with the inductor fitted. */
#ifdef NRF_LFCLK_CRYSTAL
#    define NRF_APP_LFCLK_XTAL 1
#else
#    define NRF_APP_LFCLK_XTAL 0
#endif
#ifdef NRF_POWER_DCDC_REG1
#    define NRF_APP_DCDC_REG1 1
#else
#    define NRF_APP_DCDC_REG1 0
#endif
#ifdef NRF_POWER_DCDC_REG0
#    define NRF_APP_DCDC_REG0 1
#else
#    define NRF_APP_DCDC_REG0 0
#endif

/* Battery charger, declared in the keyboard's config.h (the core keeps it
 * charging and tracks the state; see nrf_core_charge_state() in nrf_core.h):
 *
 *   #define NRF_CHARGER_EN_PIN         P1_04  // drives the charger's enable/PROG
 *   #define NRF_CHARGER_EN_ACTIVE_LOW         // enable = low (else high); off = floating
 *   #define NRF_CHARGER_STAT_PIN       P1_06  // charge status, read while USB is powered
 *   #define NRF_CHARGER_STAT_PULLUP           // or NRF_CHARGER_STAT_PULLDOWN
 *   #define NRF_CHARGER_STAT_CHARGING_LEVEL 1 // pin level while charging (else: full)
 */
#ifndef NRF_CHARGER_EN_PIN
#    define NRF_CHARGER_EN_PIN NO_PIN
#endif
#ifndef NRF_CHARGER_STAT_PIN
#    define NRF_CHARGER_STAT_PIN NO_PIN
#endif
#ifdef NRF_CHARGER_EN_ACTIVE_LOW
#    define NRF_APP_CHARGER_EN_FLAGS NRF_CHARGER_FLAG_EN_ACTIVE_LOW
#else
#    define NRF_APP_CHARGER_EN_FLAGS 0
#endif
#ifndef NRF_CHARGER_STAT_CHARGING_LEVEL
#    define NRF_CHARGER_STAT_CHARGING_LEVEL 0
#endif
#if defined(NRF_CHARGER_STAT_PULLUP) && defined(NRF_CHARGER_STAT_PULLDOWN)
#    error "NRF_CHARGER_STAT_PULLUP and NRF_CHARGER_STAT_PULLDOWN are exclusive"
#elif defined(NRF_CHARGER_STAT_PULLUP)
#    define NRF_APP_CHARGER_STAT_PULL NRF_CHARGER_FLAG_STAT_PULLUP
#elif defined(NRF_CHARGER_STAT_PULLDOWN)
#    define NRF_APP_CHARGER_STAT_PULL NRF_CHARGER_FLAG_STAT_PULLDOWN
#else
#    define NRF_APP_CHARGER_STAT_PULL 0
#endif
#define NRF_APP_CHARGER_STAT_FLAGS \
    (NRF_APP_CHARGER_STAT_PULL | (NRF_CHARGER_STAT_CHARGING_LEVEL ? NRF_CHARGER_FLAG_STAT_CHARGING_HIGH : 0))

/* image_size and crc32 are filled in by nrf_app_pack.py after linking. */
__attribute__((section(".app_header"), used)) const struct nrf_app_header nrf_app_header = {
    .magic       = NRF_APP_MAGIC,
    .abi_major   = NRF_CORE_ABI_MAJOR,
    .abi_minor   = NRF_CORE_ABI_MINOR,
    .header_size = sizeof(struct nrf_app_header),
    .chip        = NRF_CHIP,
    .load_addr   = (uint32_t)__app_flash_start,
    .image_size  = 0xFFFFFFFFu,
    .ram_start   = (uint32_t)__app_ram_start,
    .ram_end     = (uint32_t)__app_ram_end,
    .entry       = nrf_app_entry,
    .crc32       = 0xFFFFFFFFu,
    .abi_hash    = NRF_CORE_ABI_HASH,
    .identity =
        {
            .vid          = VENDOR_ID,
            .pid          = PRODUCT_ID,
            .device_ver   = DEVICE_VER,
            .reserved     = 0,
            .manufacturer = nrf_app_manufacturer,
            .product      = PRODUCT,
        },
    .battery =
        {
            .method        = NRF_BATTERY_METHOD,
            .pin           = (uint8_t)NRF_BATTERY_PIN,
            .en_pin        = (uint8_t)NRF_BATTERY_EN_PIN,
            .en_active_low = NRF_BATTERY_EN_LOW,
            .r_top_ohms    = NRF_BATTERY_R_TOP,
            .r_bottom_ohms = NRF_BATTERY_R_BOTTOM,
            .settle_us     = NRF_BATTERY_SETTLE_US,
            .empty_mv      = NRF_BATTERY_EMPTY_MV,
            .full_mv       = NRF_BATTERY_FULL_MV,
            .reserved      = 0,
        },
    .power =
        {
            .lfclk_xtal = NRF_APP_LFCLK_XTAL,
            .dcdc_reg1  = NRF_APP_DCDC_REG1,
            .dcdc_reg0  = NRF_APP_DCDC_REG0,
            .reserved   = 0,
        },
    .charger =
        {
            .en_pin     = (uint8_t)NRF_CHARGER_EN_PIN,
            .en_flags   = NRF_APP_CHARGER_EN_FLAGS,
            .stat_pin   = (uint8_t)NRF_CHARGER_STAT_PIN,
            .stat_flags = NRF_APP_CHARGER_STAT_FLAGS,
        },
};
